def test_page(t):
    url = f"{SITE}/tests/{t['slug']}/"
    rev = set(t.get("reverse", []))
    qs = []
    for i, item in enumerate(t["items"], start=1):
        options = t["options"]
        if t["kind"] == "ecr":
            text, sub, r = item
            attrs = f' data-sub="{sub}" data-rev="{1 if r else 0}"'
        elif t["kind"] == "multi":
            text, sub, r = item[:3]
            if len(item) > 3:
                options = t["option_sets"][item[3]]
            attrs = f' data-sub="{sub}"'
        else:
            text, attrs, r = item, "", False
        opts = []
        n = len(options)
        vals = [v for _, v in options]
        for label, val in options:
            if t["kind"] == "multi":
                v = (min(vals) + max(vals)) - val if r else val  # reverse-keyed items
            else:
                v = (n - 1) - val if (i in rev) else val  # reverse-keyed items (Rosenberg)
            opts.append(f'<label class="opt"><input type="radio" name="q{i}" value="{v}" required><span>{esc(label)}</span></label>')

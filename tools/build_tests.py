def count_label(n):
    return f"{n} أسئلة" if 3 <= n <= 10 else f"{n} سؤال"


def ref_short(src):
    """'Fraley, R. C., ... (2011). Title...' -> 'Fraley وزملاؤه (2011)'"""
    import re as _re
    m = _re.match(r"\s*([^,]+),.*?\((\d{4})\)", src)
    if not m:
        return ""
    head = src[:m.end()]
    if head.count(",") > 3:
        return f"{m.group(1)} وزملاؤه ({m.group(2)})"
    two = _re.search(r"&\s*([^,]+),", head)
    return f"{m.group(1)}{(' و' + two.group(1)) if two else ''} ({m.group(2)})"


